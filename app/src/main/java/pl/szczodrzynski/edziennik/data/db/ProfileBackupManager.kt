package pl.szczodrzynski.edziennik.data.db

import android.content.ContentValues
import android.database.Cursor
import android.database.sqlite.SQLiteDatabase
import android.util.Base64
import androidx.sqlite.db.SupportSQLiteDatabase
import com.google.gson.JsonArray
import com.google.gson.JsonElement
import com.google.gson.JsonObject
import com.google.gson.JsonParser
import com.google.gson.stream.JsonWriter
import pl.szczodrzynski.edziennik.data.enums.LoginType
import java.io.Reader
import java.io.Writer
import kotlin.math.max

class ProfileBackupManager(
    private val roomDb: AppDb,
) {
    companion object {
        private const val FORMAT_VERSION = 1
        private const val PROFILE_TABLE = "profiles"
        private const val PROFILE_ID = "profileId"
        private const val IMPORTED_UI_FEATURES = "importedUiFeatures"

        private val autoGeneratedColumns = mapOf(
            "metadata" to "metadataId",
            "notifications" to "id",
            "timetableManual" to "id",
        )

        private val preferredImportOrder = listOf(
            PROFILE_TABLE,
            "teachers",
            "subjects",
            "teams",
            "lessonRanges",
            "gradeCategories",
            "classrooms",
            "attendanceTypes",
            "noticeTypes",
            "eventTypes",
            "teacherAbsenceTypes",
            "librusLessons",
            "timetable",
            "timetableManual",
            "grades",
            "events",
            "notices",
            "attendances",
            "announcements",
            "luckyNumbers",
            "teacherAbsence",
            "messages",
            "messageRecipients",
            "notes",
            "metadata",
            "notifications",
            "config",
            "endpointTimers",
        )
    }

    private data class ColumnSchema(
        val name: String,
        val type: String,
    )

    private data class TableSchema(
        val name: String,
        val columns: LinkedHashMap<String, ColumnSchema>,
    )

    fun export(profileId: Int, output: Writer) {
        val database = roomDb.openHelper.readableDatabase
        val tables = getProfileTables(database)
        require(tables.containsKey(PROFILE_TABLE)) { "Profile table is unavailable" }
        require(
            database.query(
                "SELECT 1 FROM ${quote(PROFILE_TABLE)} WHERE ${quote(PROFILE_ID)} = ?",
                arrayOf<Any?>(profileId),
            ).use { it.moveToFirst() }
        ) { "Profile $profileId does not exist" }

        JsonWriter(output).use { writer ->
            writer.setIndent("  ")
            writer.beginObject()
            writer.name("formatVersion").value(FORMAT_VERSION.toLong())
            writer.name("databaseVersion").value(database.version.toLong())
            writer.name("sourceProfileId").value(profileId.toLong())
            writer.name("tables").beginObject()

            tables.values.forEach { table ->
                writer.name(table.name).beginArray()
                database.query(
                    "SELECT * FROM ${quote(table.name)} WHERE ${quote(PROFILE_ID)} = ?",
                    arrayOf<Any?>(profileId),
                ).use { cursor ->
                    while (cursor.moveToNext()) {
                        writer.beginObject()
                        cursor.columnNames.forEachIndexed { index, columnName ->
                            writer.name(columnName)
                            writeValue(writer, cursor, index)
                        }
                        writer.endObject()
                    }
                }
                writer.endArray()
            }

            writer.endObject()
            writer.endObject()
        }
    }

    fun import(targetProfileId: Int, input: Reader) {
        val backup = JsonParser.parseReader(input).asJsonObject
        val formatVersion = backup.requiredInt("formatVersion")
        require(formatVersion == FORMAT_VERSION) {
            "Unsupported profile backup format: $formatVersion"
        }

        val database = roomDb.openHelper.writableDatabase
        val databaseVersion = backup.requiredInt("databaseVersion")
        require(databaseVersion <= database.version) {
            "Backup database version $databaseVersion is newer than ${database.version}"
        }

        val sourceProfileId = backup.requiredInt("sourceProfileId")
        val backupTables = backup.getAsJsonObject("tables")
            ?: throw IllegalArgumentException("Profile backup does not contain tables")
        require(backupTables.has(PROFILE_TABLE)) {
            "Profile backup does not contain a profile"
        }

        val currentTables = getProfileTables(database)
        if (databaseVersion == database.version) {
            val missingTables = currentTables.keys - backupTables.keySet()
            require(missingTables.isEmpty()) {
                "Profile backup is incomplete: ${missingTables.joinToString()}"
            }
        }

        val currentIdentity = getCurrentProfileIdentity(database, targetProfileId)
        val importedRows = currentTables.mapValuesTo(linkedMapOf()) { (tableName, _) ->
            backupTables.getAsJsonArray(tableName)
                ?.map {
                    val row = it.asJsonObject.deepCopy()
                    require(row.get(PROFILE_ID)?.asInt == sourceProfileId) {
                        "Table $tableName contains data from another profile"
                    }
                    row
                }
                ?.toMutableList()
                ?: mutableListOf()
        }
        addImportedUiFeatures(importedRows, sourceProfileId)

        roomDb.runInTransaction {
            val noteIdMap = remapConflictingNoteIds(
                database = database,
                targetProfileId = targetProfileId,
                noteRows = importedRows["notes"].orEmpty(),
            )
            remapNotificationNoteIds(importedRows["notifications"].orEmpty(), noteIdMap)

            currentTables.values
                .filter { it.name != PROFILE_TABLE }
                .forEach { table ->
                    database.delete(
                        table.name,
                        "$PROFILE_ID = ?",
                        arrayOf<Any?>(targetProfileId),
                    )
                }
            database.delete(
                PROFILE_TABLE,
                "$PROFILE_ID = ?",
                arrayOf<Any?>(targetProfileId),
            )

            currentTables.values
                .sortedWith(
                    compareBy<TableSchema> {
                        preferredImportOrder.indexOf(it.name).let { index ->
                            if (index == -1) Int.MAX_VALUE else index
                        }
                    }.thenBy { it.name }
                )
                .forEach { table ->
                    importedRows[table.name].orEmpty().forEach { row ->
                        row.addProperty(PROFILE_ID, targetProfileId)
                        if (table.name == PROFILE_TABLE) {
                            row.add(PROFILE_ID, currentIdentity.get(PROFILE_ID))
                            row.add("loginStoreId", currentIdentity.get("loginStoreId"))
                            row.add("loginStoreType", currentIdentity.get("loginStoreType"))
                        }
                        insertRow(database, table, row)
                    }
                }

            require(
                database.query(
                    "SELECT 1 FROM ${quote(PROFILE_TABLE)} WHERE ${quote(PROFILE_ID)} = ?",
                    arrayOf<Any?>(targetProfileId),
                ).use { it.moveToFirst() }
            ) { "Imported profile row is missing" }
        }
    }

    private fun addImportedUiFeatures(
        importedRows: MutableMap<String, MutableList<JsonObject>>,
        sourceProfileId: Int,
    ) {
        val profileRow = importedRows[PROFILE_TABLE]?.singleOrNull()
            ?: throw IllegalArgumentException("Profile backup must contain exactly one profile")
        val sourceLoginTypeId = profileRow.get("loginStoreType")?.asInt
            ?: throw IllegalArgumentException("Profile backup does not contain a login type")
        val sourceLoginType = LoginType.entries.firstOrNull { it.id == sourceLoginTypeId }
            ?: throw IllegalArgumentException("Unknown login type: $sourceLoginTypeId")

        val configRows = importedRows["config"]
            ?: throw IllegalArgumentException("Profile backup does not contain profile config")
        val importedFeatureNames = configRows
            .firstOrNull { it.get("key")?.asString == IMPORTED_UI_FEATURES }
            ?.get("value")
            ?.takeUnless(JsonElement::isJsonNull)
            ?.asString
            ?.let { value ->
                runCatching {
                    JsonParser.parseString(value).asJsonArray.map { it.asString }
                }.getOrDefault(emptyList())
            }
            .orEmpty()
        val featureNames = (sourceLoginType.features.map { it.name } + importedFeatureNames)
            .distinct()

        configRows.removeAll { it.get("key")?.asString == IMPORTED_UI_FEATURES }
        configRows += JsonObject().apply {
            addProperty(PROFILE_ID, sourceProfileId)
            addProperty("key", IMPORTED_UI_FEATURES)
            addProperty("value", JsonArray().apply {
                featureNames.forEach(::add)
            }.toString())
        }
    }

    private fun getProfileTables(database: SupportSQLiteDatabase): LinkedHashMap<String, TableSchema> {
        val result = linkedMapOf<String, TableSchema>()
        database.query(
            "SELECT name FROM sqlite_master " +
                "WHERE type = 'table' AND name NOT LIKE 'sqlite_%' ORDER BY name"
        ).use { tables ->
            while (tables.moveToNext()) {
                val tableName = tables.getString(0)
                val columns = linkedMapOf<String, ColumnSchema>()
                database.query("PRAGMA table_info(${quote(tableName)})").use { cursor ->
                    val nameIndex = cursor.getColumnIndexOrThrow("name")
                    val typeIndex = cursor.getColumnIndexOrThrow("type")
                    while (cursor.moveToNext()) {
                        val name = cursor.getString(nameIndex)
                        columns[name] = ColumnSchema(name, cursor.getString(typeIndex).orEmpty())
                    }
                }
                if (tableName == PROFILE_TABLE || columns.containsKey(PROFILE_ID)) {
                    result[tableName] = TableSchema(tableName, columns)
                }
            }
        }
        return result
    }

    private fun getCurrentProfileIdentity(
        database: SupportSQLiteDatabase,
        profileId: Int,
    ): JsonObject {
        return database.query(
            "SELECT ${quote(PROFILE_ID)}, ${quote("loginStoreId")}, ${quote("loginStoreType")} " +
                "FROM ${quote(PROFILE_TABLE)} WHERE ${quote(PROFILE_ID)} = ?",
            arrayOf<Any?>(profileId),
        ).use { cursor ->
            require(cursor.moveToFirst()) { "Current profile does not exist" }
            JsonObject().also { identity ->
                cursor.columnNames.forEachIndexed { index, name ->
                    identity.add(name, cursorValue(cursor, index))
                }
            }
        }
    }

    private fun remapConflictingNoteIds(
        database: SupportSQLiteDatabase,
        targetProfileId: Int,
        noteRows: List<JsonObject>,
    ): Map<Long, Long> {
        if (noteRows.isEmpty())
            return emptyMap()

        var nextId = database.query("SELECT MAX(noteId) FROM notes").use { cursor ->
            val maxId = if (cursor.moveToFirst() && !cursor.isNull(0)) cursor.getLong(0) else 0L
            max(System.currentTimeMillis(), maxId + 1)
        }
        val usedIds = noteRows.mapNotNull { it.get("noteId")?.asLong }.toMutableSet()
        val idMap = mutableMapOf<Long, Long>()

        noteRows.forEach { row ->
            val oldId = row.get("noteId")?.asLong ?: return@forEach
            val hasConflict = database.query(
                "SELECT 1 FROM notes WHERE noteId = ? AND profileId != ? LIMIT 1",
                arrayOf<Any?>(oldId, targetProfileId),
            ).use { it.moveToFirst() }
            if (hasConflict) {
                while (nextId in usedIds)
                    nextId++
                val newId = nextId++
                row.addProperty("noteId", newId)
                usedIds += newId
                idMap[oldId] = newId
            }
        }
        return idMap
    }

    private fun remapNotificationNoteIds(
        notificationRows: List<JsonObject>,
        noteIdMap: Map<Long, Long>,
    ) {
        if (noteIdMap.isEmpty())
            return

        notificationRows.forEach { row ->
            val extrasString = row.get("extras")
                ?.takeUnless(JsonElement::isJsonNull)
                ?.asString
                ?: return@forEach
            val extras = runCatching {
                JsonParser.parseString(extrasString).asJsonObject
            }.getOrNull() ?: return@forEach
            val oldNoteId = extras.get("noteId")?.asLong ?: return@forEach
            val newNoteId = noteIdMap[oldNoteId] ?: return@forEach
            extras.addProperty("noteId", newNoteId)
            row.addProperty("extras", extras.toString())
        }
    }

    private fun insertRow(
        database: SupportSQLiteDatabase,
        table: TableSchema,
        row: JsonObject,
    ) {
        val values = ContentValues()
        val generatedColumn = autoGeneratedColumns[table.name]
        table.columns.values.forEach { column ->
            if (column.name == generatedColumn)
                return@forEach
            val value = row.get(column.name) ?: return@forEach
            putValue(values, column, value)
        }
        val result = database.insert(table.name, SQLiteDatabase.CONFLICT_ABORT, values)
        check(result != -1L) { "Unable to import table ${table.name}" }
    }

    private fun putValue(values: ContentValues, column: ColumnSchema, value: JsonElement) {
        if (value.isJsonNull) {
            values.putNull(column.name)
            return
        }
        if (value.isJsonObject && value.asJsonObject.has("\$blob")) {
            values.put(
                column.name,
                Base64.decode(value.asJsonObject.get("\$blob").asString, Base64.NO_WRAP),
            )
            return
        }

        val primitive = value.asJsonPrimitive
        when (column.type.uppercase()) {
            in listOf("REAL", "FLOAT", "DOUBLE") ->
                values.put(column.name, primitive.asDouble)
            in listOf("TEXT", "CHAR", "CLOB") ->
                values.put(column.name, primitive.asString)
            in listOf("BLOB") ->
                values.put(column.name, Base64.decode(primitive.asString, Base64.NO_WRAP))
            else -> {
                if (primitive.isNumber)
                    values.put(column.name, primitive.asLong)
                else
                    values.put(column.name, primitive.asString)
            }
        }
    }

    private fun writeValue(writer: JsonWriter, cursor: Cursor, index: Int) {
        when (cursor.getType(index)) {
            Cursor.FIELD_TYPE_NULL -> writer.nullValue()
            Cursor.FIELD_TYPE_INTEGER -> writer.value(cursor.getLong(index))
            Cursor.FIELD_TYPE_FLOAT -> writer.value(cursor.getDouble(index))
            Cursor.FIELD_TYPE_STRING -> writer.value(cursor.getString(index))
            Cursor.FIELD_TYPE_BLOB -> {
                writer.beginObject()
                writer.name("\$blob").value(
                    Base64.encodeToString(cursor.getBlob(index), Base64.NO_WRAP)
                )
                writer.endObject()
            }
            else -> writer.nullValue()
        }
    }

    private fun cursorValue(cursor: Cursor, index: Int): JsonElement {
        return when (cursor.getType(index)) {
            Cursor.FIELD_TYPE_NULL -> com.google.gson.JsonNull.INSTANCE
            Cursor.FIELD_TYPE_INTEGER -> com.google.gson.JsonPrimitive(cursor.getLong(index))
            Cursor.FIELD_TYPE_FLOAT -> com.google.gson.JsonPrimitive(cursor.getDouble(index))
            Cursor.FIELD_TYPE_STRING -> com.google.gson.JsonPrimitive(cursor.getString(index))
            Cursor.FIELD_TYPE_BLOB -> JsonObject().apply {
                addProperty(
                    "\$blob",
                    Base64.encodeToString(cursor.getBlob(index), Base64.NO_WRAP),
                )
            }
            else -> com.google.gson.JsonNull.INSTANCE
        }
    }

    private fun JsonObject.requiredInt(name: String): Int {
        return get(name)?.takeUnless(JsonElement::isJsonNull)?.asInt
            ?: throw IllegalArgumentException("Profile backup does not contain $name")
    }

    private fun quote(identifier: String) = "\"${identifier.replace("\"", "\"\"")}\""
}
